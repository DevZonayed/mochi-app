export interface DeviceRevocationMessage {
  readonly family: 'device-revocation';
  readonly v: 1;
  readonly fence: Fence;
  readonly controllerDeviceId: string;
  readonly revokedAt: number;
  readonly keyRotationId: string;
  readonly signature: string;
}

export interface KeyRotationMessage {
  readonly family: 'key-rotation';
  readonly v: 1;
  readonly fence: Fence;
  readonly keyId: string;
  readonly previousKeyId: string;
  readonly effectiveSeq: number;
  readonly createdAt: number;
  readonly signature: string;
}

function revokeSigningInput(m: Omit<DeviceRevocationMessage, 'signature'>): Uint8Array {
  return structuredEncode(DOMAIN_REVOKE_SIG, [m.fence.accountId, m.fence.scopeId, m.fence.hostDeviceId, m.fence.epoch, m.fence.leaseId, m.controllerDeviceId, m.revokedAt, m.keyRotationId]);
}

function rotateSigningInput(m: Omit<KeyRotationMessage, 'signature'>): Uint8Array {
  return structuredEncode(DOMAIN_ROTATE_SIG, [m.fence.accountId, m.fence.scopeId, m.fence.hostDeviceId, m.fence.epoch, m.fence.leaseId, m.keyId, m.previousKeyId, m.effectiveSeq, m.createdAt]);
}

export async function signDeviceRevocation(backend: ShadowCryptoBackend, host: ShadowIdentity, m: Omit<DeviceRevocationMessage, 'signature'>): Promise<DeviceRevocationMessage> {
  const signature = await backend.sign(host.keys.signing.privateKey, revokeSigningInput(m));
  return { ...m, signature: base64urlEncode(signature) };
}

export async function verifyDeviceRevocation(backend: ShadowCryptoBackend, hostSigningPublicKey: Uint8Array, m: DeviceRevocationMessage): Promise<boolean> {
  try {
    return await backend.verify(hostSigningPublicKey, revokeSigningInput(m), base64urlDecode(m.signature));
  } catch {
    return false;
  }
}

export async function signKeyRotation(backend: ShadowCryptoBackend, host: ShadowIdentity, m: Omit<KeyRotationMessage, 'signature'>): Promise<KeyRotationMessage> {
  const signature = await backend.sign(host.keys.signing.privateKey, rotateSigningInput(m));
  return { ...m, signature: base64urlEncode(signature) };
}

export async function verifyKeyRotation(backend: ShadowCryptoBackend, hostSigningPublicKey: Uint8Array, m: KeyRotationMessage): Promise<boolean> {
  try {
    return await backend.verify(hostSigningPublicKey, rotateSigningInput(m), base64urlDecode(m.signature));
  } catch {
    return false;
  }
}

/**
 * Rotate the scope key for the set of controllers that remain after a revocation.
 * The revoked controller is excluded, so it can never receive the new key. Each
 * remaining controller receives the SAME new scope key wrapped to its own X25519
 * key — no split brain. Callers pass the per-controller agreement public keys and
 * the transcript hash captured at that controller's enrollment.
 */
export async function rotateScopeKeyForControllers(
  backend: ShadowCryptoBackend,
  input: {
    host: ShadowIdentity;
    fence: Fence; // NEW fence (post-rotation epoch)
    revokedControllerDeviceId: string;
    remaining: ReadonlyArray<{ controllerDeviceId: string; agreementPublicKey: Uint8Array; transcriptHash: Uint8Array; capabilities?: readonly ShadowCapability[] }>;
    nowMs: number;
    ttlMs?: number;
  },
): Promise<{ scopeKey: Uint8Array; scopeKeyId: string; perController: EnrollmentApproval[] }> {
  const scopeKey = backend.randomBytes(SHADOW_SCOPE_KEY_BYTES);
  const perController: EnrollmentApproval[] = [];
  for (const c of input.remaining) {
    if (c.controllerDeviceId === input.revokedControllerDeviceId) continue; // defensive: never wrap to revoked
    const approval = await approveEnrollment(backend, {
      host: input.host, fence: input.fence, controllerDeviceId: c.controllerDeviceId,
      controllerAgreementPublicKey: c.agreementPublicKey, transcriptHash: c.transcriptHash,
      sessionId: 'rotation', nowMs: input.nowMs, ttlMs: input.ttlMs, scopeKey,
      // Preserve each remaining controller's approved capability set across rotation
      // (never silently widen/downgrade). Undefined stays legacy account.read.
      capabilities: c.capabilities,
    });
    perController.push(approval);
  }
  const scopeKeyId = perController[0]?.scopeKeyId ?? 'wk_' + base64urlEncode(await structuredDigest(backend, 'maestro.shadow.scope-key.v1', [input.fence.accountId, input.fence.scopeId, scopeKey]));
  return { scopeKey, scopeKeyId, perController };
}
