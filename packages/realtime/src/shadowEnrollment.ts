export interface ShadowIdentityKeys {
  readonly signing: ShadowKeyPair;
  readonly agreement: ShadowKeyPair;
}

export interface ShadowIdentityPublic {
  readonly deviceId: string;
  readonly signingPublicKey: Uint8Array;
  readonly agreementPublicKey: Uint8Array;
  readonly signingKeyId: string;
  readonly agreementKeyId: string;
}

export interface ShadowIdentity extends ShadowIdentityPublic {
  readonly keys: ShadowIdentityKeys;
}

/** Generate a fresh device identity (distinct Ed25519 + X25519 keys) from the CSPRNG. */
export async function generateShadowIdentity(backend: ShadowCryptoBackend, deviceId: string): Promise<ShadowIdentity> {
  const signing = await backend.generateSigningKeyPair();
  const agreement = await backend.generateAgreementKeyPair();
  return materializeIdentity(backend, deviceId, { signing, agreement });
}

/** Rebuild the public projection + key ids for a persisted identity keypair. */
export async function materializeIdentity(backend: ShadowCryptoBackend, deviceId: string, keys: ShadowIdentityKeys): Promise<ShadowIdentity> {
  const signingKeyId = await keyFingerprint(backend, 'sign', keys.signing.publicKey);
  const agreementKeyId = await keyFingerprint(backend, 'agree', keys.agreement.publicKey);
  return {
    deviceId,
    keys,
    signingPublicKey: keys.signing.publicKey,
    agreementPublicKey: keys.agreement.publicKey,
    signingKeyId,
    agreementKeyId,
  };
}

