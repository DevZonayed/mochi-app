// One-time secret + verifier
// ---------------------------------------------------------------------------

export interface EnrollmentSecretVerifier {
  readonly salt: string; // base64url
  readonly verifier: string; // base64url, peppered HMAC — safe at rest
}

/** Binding hash of the one-time secret to its session + account (never the raw secret). */
async function secretBinding(backend: ShadowCryptoBackend, sessionId: string, accountId: string, secret: Uint8Array): Promise<Uint8Array> {
  const secretDigest = await backend.sha256(secret);
  return structuredDigest(backend, DOMAIN_SECRET_BINDING, [sessionId, accountId, secretDigest]);
}

/**
 * Server-side verifier of the one-time secret: HMAC(serverPepper, salt || binding).
 * Stored at rest; the plaintext secret is never persisted. `pepper` is a
 * server-only key; `salt` is per-session random.
 */
export async function makeEnrollmentSecretVerifier(
  backend: ShadowCryptoBackend,
  input: { sessionId: string; accountId: string; secret: Uint8Array; salt: Uint8Array; pepper: Uint8Array },
): Promise<EnrollmentSecretVerifier> {
  const binding = await secretBinding(backend, input.sessionId, input.accountId, input.secret);
  const mac = await backend.hmacSha256(input.pepper, structuredEncode(DOMAIN_SECRET_VERIFIER, [input.sessionId, input.accountId, input.salt, binding]));
  return { salt: base64urlEncode(input.salt), verifier: base64urlEncode(mac) };
}

/** Constant-time verification of a presented secret against the stored peppered verifier. */
export async function verifyEnrollmentSecret(
  backend: ShadowCryptoBackend,
  input: { sessionId: string; accountId: string; presentedSecret: Uint8Array; stored: EnrollmentSecretVerifier; pepper: Uint8Array },
): Promise<boolean> {
  let salt: Uint8Array;
  let expected: Uint8Array;
  try {
    salt = base64urlDecode(input.stored.salt);
    expected = base64urlDecode(input.stored.verifier);
  } catch {
    return false;
  }
  const binding = await secretBinding(backend, input.sessionId, input.accountId, input.presentedSecret);
  const mac = await backend.hmacSha256(input.pepper, structuredEncode(DOMAIN_SECRET_VERIFIER, [input.sessionId, input.accountId, salt, binding]));
  return constantTimeEqual(mac, expected);
}

