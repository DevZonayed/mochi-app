/**
 * shadowEnrollment — one-time, account-bound controller enrollment, scope-key
 * wrapping, revocation and key rotation, built purely on {@link ShadowCryptoBackend}.
 *
 * Trust / secrecy contract enforced here (see REPORT threat model):
 *   - Controller & host each hold distinct Ed25519 (signing) + X25519 (agreement)
 *     keys. Private material never leaves the owning tier; only raw public keys,
 *     signatures, and AEAD ciphertext cross the wire.
 *   - The one-time enrollment secret (256-bit) is carried only in the QR/deep-link
 *     bootstrap and proven to the server against a peppered verifier; the server
 *     never stores the plaintext secret and never learns any private key or the
 *     decrypted scope key.
 *   - A transcript hash binds session id, account, host device, both host public
 *     keys, controller device, both controller public keys, relay origin and a
 *     nonce. Every signature and the scope-key wrap are bound to it, so replacing
 *     any bound value invalidates the flow.
 *   - The scope key is freshly generated by the host and wrapped to the controller
 *     X25519 key via transcript-salted HKDF-SHA256 + AES-256-GCM. The relay only
 *     ever transports/stores the ciphertext + public metadata.
 *
 * The compact, exact-keyed wire families (`enrollment-request`, `enrollment-grant`,
 * `device-revocation`, `key-rotation`) defined in `./shadowProtocol` are the SIGNED
 * control notifications; the richer request/grant/key-material records defined here
 * are the transcript + ciphertext the relay stores. Signatures produced here are
 * real Ed25519 signatures (base64url) that also satisfy the protocol decoders.
 */
