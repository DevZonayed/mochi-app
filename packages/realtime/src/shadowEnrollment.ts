export interface EnrollmentBootstrap {
  readonly scheme: typeof SHADOW_ENROLLMENT_BOOTSTRAP_SCHEME;
  readonly v: typeof SHADOW_ENROLLMENT_BOOTSTRAP_VERSION;
  readonly sessionId: string;
  readonly accountId: string;
  readonly hostDeviceId: string;
  readonly hostSigningKeyId: string;
  readonly hostSigningPublicKey: string; // base64url raw
  readonly hostAgreementPublicKey: string; // base64url raw
  readonly relayOrigin: string;
  readonly secret: string; // base64url one-time secret (bootstrap only; not a key)
  readonly expiresAt: number;
}

export interface EnrollmentSessionCreation {
  readonly sessionId: string;
  readonly bootstrap: EnrollmentBootstrap;
  /** Server-stored record — carries NO plaintext secret and NO private keys. */
  readonly serverRecord: EnrollmentServerRecord;
  /** The raw secret is returned once to the caller (host) to render the QR, then discarded. */
  readonly secret: Uint8Array;
}

export interface EnrollmentServerRecord {
  readonly sessionId: string;
  readonly accountId: string;
  readonly hostDeviceId: string;
  readonly hostSigningKeyId: string;
  readonly relayOrigin: string;
  readonly secretVerifier: EnrollmentSecretVerifier;
  readonly createdAt: number;
  readonly expiresAt: number;
}

/**
 * Host-side session creation. Produces the QR bootstrap (with the one-time secret)
 * and the server record (with only the peppered verifier). `idOf` supplies random
 * ids from the caller so the module stays free of ambient time/RNG beyond `backend`.
 */
export async function createEnrollmentSession(
  backend: ShadowCryptoBackend,
  input: {
    host: ShadowIdentityPublic;
    accountId: string;
    relayOrigin: string;
    nowMs: number;
    ttlMs?: number;
    serverPepper: Uint8Array;
    sessionId?: string;
  },
): Promise<EnrollmentSessionCreation> {
  const ttl = Math.min(input.ttlMs ?? SHADOW_ENROLLMENT_SESSION_MAX_TTL_MS, SHADOW_ENROLLMENT_SESSION_MAX_TTL_MS);
  const sessionId = input.sessionId ?? 'es_' + base64urlEncode(backend.randomBytes(18));
  const secret = backend.randomBytes(SHADOW_ENROLLMENT_SECRET_BYTES);
  const salt = backend.randomBytes(16);
  const expiresAt = input.nowMs + ttl;
  const secretVerifier = await makeEnrollmentSecretVerifier(backend, { sessionId, accountId: input.accountId, secret, salt, pepper: input.serverPepper });
  const bootstrap: EnrollmentBootstrap = {
    scheme: SHADOW_ENROLLMENT_BOOTSTRAP_SCHEME,
    v: SHADOW_ENROLLMENT_BOOTSTRAP_VERSION,
    sessionId,
    accountId: input.accountId,
    hostDeviceId: input.host.deviceId,
    hostSigningKeyId: input.host.signingKeyId,
    hostSigningPublicKey: base64urlEncode(input.host.signingPublicKey),
    hostAgreementPublicKey: base64urlEncode(input.host.agreementPublicKey),
    relayOrigin: input.relayOrigin,
    secret: base64urlEncode(secret),
    expiresAt,
  };
  const serverRecord: EnrollmentServerRecord = {
    sessionId,
    accountId: input.accountId,
    hostDeviceId: input.host.deviceId,
    hostSigningKeyId: input.host.signingKeyId,
    relayOrigin: input.relayOrigin,
    secretVerifier,
    createdAt: input.nowMs,
    expiresAt,
  };
  return { sessionId, bootstrap, serverRecord, secret };
}

export function encodeEnrollmentBootstrap(bootstrap: EnrollmentBootstrap): string {
  // Compact, URL-safe deep link. Field order fixed; values are already url-safe.
  const params = new URLSearchParams({
    v: String(bootstrap.v),
    s: bootstrap.sessionId,
    a: bootstrap.accountId,
    h: bootstrap.hostDeviceId,
    hk: bootstrap.hostSigningKeyId,
    hsp: bootstrap.hostSigningPublicKey,
    hap: bootstrap.hostAgreementPublicKey,
    o: bootstrap.relayOrigin,
    sec: bootstrap.secret,
    e: String(bootstrap.expiresAt),
  });
  return `${SHADOW_ENROLLMENT_BOOTSTRAP_SCHEME}://enroll?${params.toString()}`;
}

export function decodeEnrollmentBootstrap(
  value: string,
  options: { allowedOrigins: readonly string[]; nowMs: number },
): { ok: true; value: EnrollmentBootstrap } | { ok: false; reason: string } {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    return { ok: false, reason: 'bad-url' };
  }
  if (url.protocol !== `${SHADOW_ENROLLMENT_BOOTSTRAP_SCHEME}:`) return { ok: false, reason: 'bad-scheme' };
  if (url.host !== 'enroll' && url.pathname.replace(/^\/+/, '') !== 'enroll') return { ok: false, reason: 'bad-action' };
  const q = url.searchParams;
  const v = Number(q.get('v'));
  if (v !== SHADOW_ENROLLMENT_BOOTSTRAP_VERSION) return { ok: false, reason: 'bad-version' };
  const get = (k: string) => q.get(k) ?? '';
  const relayOrigin = get('o');
  if (!options.allowedOrigins.includes(relayOrigin)) return { ok: false, reason: 'origin-not-allowed' };
  const expiresAt = Number(get('e'));
  if (!Number.isSafeInteger(expiresAt)) return { ok: false, reason: 'bad-expiry' };
  if (options.nowMs >= expiresAt) return { ok: false, reason: 'expired' };
  if (expiresAt - options.nowMs > SHADOW_ENROLLMENT_SESSION_MAX_TTL_MS + 60_000) return { ok: false, reason: 'expiry-too-far' };
  const idRe = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$/;
  const b64 = /^[A-Za-z0-9_-]+$/;
  const sessionId = get('s'), accountId = get('a'), hostDeviceId = get('h'), hostSigningKeyId = get('hk');
  const hsp = get('hsp'), hap = get('hap'), secret = get('sec');
  if (![sessionId, accountId, hostDeviceId, hostSigningKeyId].every((x) => idRe.test(x))) return { ok: false, reason: 'bad-id' };
  if (![hsp, hap, secret].every((x) => b64.test(x))) return { ok: false, reason: 'bad-material' };
  let secretBytes: Uint8Array, sp: Uint8Array, ap: Uint8Array;
  try {
    secretBytes = base64urlDecode(secret); sp = base64urlDecode(hsp); ap = base64urlDecode(hap);
  } catch {
    return { ok: false, reason: 'bad-b64' };
  }
  if (secretBytes.length !== SHADOW_ENROLLMENT_SECRET_BYTES || sp.length !== 32 || ap.length !== 32) return { ok: false, reason: 'bad-length' };
  return {
    ok: true,
    value: {
      scheme: SHADOW_ENROLLMENT_BOOTSTRAP_SCHEME,
      v: SHADOW_ENROLLMENT_BOOTSTRAP_VERSION,
      sessionId, accountId, hostDeviceId, hostSigningKeyId,
      hostSigningPublicKey: hsp, hostAgreementPublicKey: hap,
      relayOrigin, secret, expiresAt,
    },
  };
}

