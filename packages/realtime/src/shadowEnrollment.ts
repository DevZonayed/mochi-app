export interface EnrollmentRequest {
  readonly v: number;
  readonly sessionId: string;
  readonly accountId: string;
  readonly controllerDeviceId: string;
  readonly controllerSigningKeyId: string;
  readonly controllerAgreementKeyId: string;
  readonly signingPublicKey: string; // base64url raw
  readonly agreementPublicKey: string; // base64url raw
  readonly nonce: string; // base64url
  readonly requestedAt: number;
  readonly transcriptHash: string; // base64url
  /**
   * Canonical (sorted, deduped, bounded) capability set the CONTROLLER requests,
   * bound into the controller-signed request proof. OPTIONAL for byte-additive
   * legacy compatibility: a request with no field is treated as `account.read` only.
   * The host may only ever approve a subset of this verified set (see approveEnrollment).
   */
  readonly requestedCapabilities?: readonly ShadowCapability[];
  readonly signature: string; // base64url Ed25519 over request transcript
}

async function requestSigningInput(backend: ShadowCryptoBackend, r: Omit<EnrollmentRequest, 'signature'>, bootstrap: { hostSigningPublicKey: Uint8Array; hostAgreementPublicKey: Uint8Array; relayOrigin: string }): Promise<Uint8Array> {
  const parts: Array<string | number | Uint8Array> = [
    r.sessionId, r.accountId, r.controllerDeviceId,
    base64urlDecode(r.signingPublicKey), base64urlDecode(r.agreementPublicKey),
    bootstrap.hostSigningPublicKey, bootstrap.hostAgreementPublicKey, bootstrap.relayOrigin,
    base64urlDecode(r.nonce), r.requestedAt, base64urlDecode(r.transcriptHash),
  ];
  // BYTE-ADDITIVE: a legacy request (no requestedCapabilities) signs exactly as before;
  // a request that carries them binds their canonical string, so any add/remove/unknown
  // breaks the controller signature. Invalid → poison marker that can never verify.
  if (r.requestedCapabilities !== undefined) {
    const canon = canonicalizeCapabilities(r.requestedCapabilities);
    parts.push(canon.ok ? `req:${capabilitiesCanonicalString(canon.capabilities)}` : '\u0000invalid-requested-capabilities');
  }
  return structuredEncode(DOMAIN_REQUEST_SIG, parts);
}

/**
 * Controller builds and signs an enrollment request from a validated bootstrap.
 * The controller proves control of its signing private key over the transcript.
 * The raw one-time secret is returned separately for presentation to the server
 * (never embedded in the signed request that is forwarded to the host).
 */
export async function buildEnrollmentRequest(
  backend: ShadowCryptoBackend,
  input: { controller: ShadowIdentity; bootstrap: EnrollmentBootstrap; nowMs: number; nonce?: Uint8Array; requestedCapabilities?: readonly ShadowCapability[] },
): Promise<{ request: EnrollmentRequest; presentedSecret: Uint8Array }> {
  const nonce = input.nonce ?? backend.randomBytes(16);
  let requestedCapabilities: readonly ShadowCapability[] | undefined;
  if (input.requestedCapabilities !== undefined) {
    const canon = canonicalizeCapabilities(input.requestedCapabilities);
    if (!canon.ok) throw new Error(`buildEnrollmentRequest: invalid requestedCapabilities (${canon.reason})`);
    requestedCapabilities = canon.capabilities;
  }
  const hostSigningPublicKey = base64urlDecode(input.bootstrap.hostSigningPublicKey);
  const hostAgreementPublicKey = base64urlDecode(input.bootstrap.hostAgreementPublicKey);
  const transcript = await enrollmentTranscriptHash(backend, {
    sessionId: input.bootstrap.sessionId,
    accountId: input.bootstrap.accountId,
    hostDeviceId: input.bootstrap.hostDeviceId,
    hostSigningPublicKey,
    hostAgreementPublicKey,
    controllerDeviceId: input.controller.deviceId,
    controllerSigningPublicKey: input.controller.signingPublicKey,
    controllerAgreementPublicKey: input.controller.agreementPublicKey,
    relayOrigin: input.bootstrap.relayOrigin,
    nonce,
  });
  const unsigned: Omit<EnrollmentRequest, 'signature'> = {
    v: SHADOW_ENROLLMENT_BOOTSTRAP_VERSION,
    sessionId: input.bootstrap.sessionId,
    accountId: input.bootstrap.accountId,
    controllerDeviceId: input.controller.deviceId,
    controllerSigningKeyId: input.controller.signingKeyId,
    controllerAgreementKeyId: input.controller.agreementKeyId,
    signingPublicKey: base64urlEncode(input.controller.signingPublicKey),
    agreementPublicKey: base64urlEncode(input.controller.agreementPublicKey),
    nonce: base64urlEncode(nonce),
    requestedAt: input.nowMs,
    transcriptHash: base64urlEncode(transcript),
    ...(requestedCapabilities ? { requestedCapabilities } : {}),
  };
  const sigInput = await requestSigningInput(backend, unsigned, { hostSigningPublicKey, hostAgreementPublicKey, relayOrigin: input.bootstrap.relayOrigin });
  const signature = await backend.sign(input.controller.keys.signing.privateKey, sigInput);
  return {
    request: { ...unsigned, signature: base64urlEncode(signature) },
    presentedSecret: base64urlDecode(input.bootstrap.secret),
  };
}

/**
 * Host/server-side verification of an enrollment request: signature over the
 * transcript by the claimed controller signing key, key-id ↔ public-key binding,
 * account/session/host binding, transcript recomputation from the ACTUAL public
 * keys, and TTL. Returns the verified transcript hash on success.
 */
export async function verifyEnrollmentRequest(
  backend: ShadowCryptoBackend,
  input: { request: EnrollmentRequest; bootstrap: EnrollmentBootstrap; expectedAccountId: string; nowMs: number },
): Promise<{ ok: true; transcriptHash: Uint8Array; controllerSigningPublicKey: Uint8Array; controllerAgreementPublicKey: Uint8Array; requestedCapabilities: ShadowCapability[] } | { ok: false; reason: string }> {
  const r = input.request;
  if (r.v !== SHADOW_ENROLLMENT_BOOTSTRAP_VERSION) return { ok: false, reason: 'bad-version' };
  // Canonicalise the presented requested-capability set (undefined → account.read
  // legacy floor); fail closed on unknown/oversized BEFORE trusting the request.
  const reqCaps = canonicalizeCapabilities(r.requestedCapabilities);
  if (!reqCaps.ok) return { ok: false, reason: `bad-requested-capabilities:${reqCaps.reason}` };
  if (r.sessionId !== input.bootstrap.sessionId) return { ok: false, reason: 'session-mismatch' };
  if (r.accountId !== input.bootstrap.accountId || r.accountId !== input.expectedAccountId) return { ok: false, reason: 'account-mismatch' };
  if (input.nowMs >= input.bootstrap.expiresAt) return { ok: false, reason: 'expired' };
  let signingPub: Uint8Array, agreementPub: Uint8Array, nonce: Uint8Array, claimedTranscript: Uint8Array, signature: Uint8Array;
  try {
    signingPub = base64urlDecode(r.signingPublicKey);
    agreementPub = base64urlDecode(r.agreementPublicKey);
    nonce = base64urlDecode(r.nonce);
    claimedTranscript = base64urlDecode(r.transcriptHash);
    signature = base64urlDecode(r.signature);
  } catch {
    return { ok: false, reason: 'bad-b64' };
  }
  if (signingPub.length !== 32 || agreementPub.length !== 32) return { ok: false, reason: 'bad-key-length' };
  const signingKeyId = await keyFingerprint(backend, 'sign', signingPub);
  const agreementKeyId = await keyFingerprint(backend, 'agree', agreementPub);
  if (signingKeyId !== r.controllerSigningKeyId || agreementKeyId !== r.controllerAgreementKeyId) return { ok: false, reason: 'key-id-mismatch' };
  const hostSigningPublicKey = base64urlDecode(input.bootstrap.hostSigningPublicKey);
  const hostAgreementPublicKey = base64urlDecode(input.bootstrap.hostAgreementPublicKey);
  const recomputed = await enrollmentTranscriptHash(backend, {
    sessionId: r.sessionId, accountId: r.accountId, hostDeviceId: input.bootstrap.hostDeviceId,
    hostSigningPublicKey, hostAgreementPublicKey,
    controllerDeviceId: r.controllerDeviceId, controllerSigningPublicKey: signingPub, controllerAgreementPublicKey: agreementPub,
    relayOrigin: input.bootstrap.relayOrigin, nonce,
  });
  if (!constantTimeEqual(recomputed, claimedTranscript)) return { ok: false, reason: 'transcript-mismatch' };
  const sigInput = await requestSigningInput(backend, { ...r }, { hostSigningPublicKey, hostAgreementPublicKey, relayOrigin: input.bootstrap.relayOrigin });
  const good = await backend.verify(signingPub, sigInput, signature);
  if (!good) return { ok: false, reason: 'bad-signature' };
  return { ok: true, transcriptHash: recomputed, controllerSigningPublicKey: signingPub, controllerAgreementPublicKey: agreementPub, requestedCapabilities: reqCaps.capabilities };
}

